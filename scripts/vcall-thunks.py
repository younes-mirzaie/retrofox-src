"""Writes correct "vcall" thunks for libxul on Windows ARM (32-bit).

With the Microsoft C++ ABI, a pointer to a virtual member function points at a small thunk that
loads the function from the vtable and jumps to it (??_9Class@@$B<offset>AA). clang 23 emits these
for thumbv7-windows as

    ldr r1, [r0]          ; vtable
    ldr r1, [r1, #offset] ; function
    bx  r1

which overwrites r1, the first argument after `this`. Every call through such a member pointer
then gets the target's own address as its first argument (seen in Gecko's chrome manifest
parsing: nsChromeRegistry::ManifestProcessingContext& arrived as a code address).

The thunks are COMDAT "pick any" functions, and lld keeps the first definition it reads. So this
script lists every thunk the build's objects define and writes them again, using r12 (the
intra-procedure scratch register) and leaving r0-r3 alone:

    ldr.w r12, [r0]
    ldr.w pc, [r12, #offset]

into RfxVcallThunks.cpp, which toolkit/library links ahead of everything else.

Usage: python vcall-thunks.py OBJDIR OUT.cpp     (prints how many thunks; exit 0)
"""
import os
import re
import subprocess
import sys

NM = r"C:\Program Files\LLVM\bin\llvm-nm.exe"
THUNK = re.compile(r"^\?\?_9.*\$B(?P<num>[0-9]|[A-P]+@)A[A-Z]$")


def ms_number(text):
    """Decodes a Microsoft mangled number: 0-9 mean 1-10, else hex digits A-P ending in @."""
    if text[0].isdigit():
        return int(text[0]) + 1
    value = 0
    for c in text[:-1]:
        value = value * 16 + (ord(c) - ord("A"))
    return value


def thunks_in(objdir, skip):
    objs = []
    for root, dirs, files in os.walk(objdir):
        for f in files:
            if f.endswith(".obj") and f != skip:
                objs.append(os.path.join(root, f))
    found = {}
    # llvm-nm on batches of files, defined symbols only
    for i in range(0, len(objs), 200):
        out = subprocess.run([NM, "--defined-only", "--no-sort"] + objs[i:i + 200],
                             capture_output=True, text=True, errors="replace").stdout
        for line in out.splitlines():
            parts = line.split()
            if len(parts) == 3 and parts[1] in ("T", "t"):
                m = THUNK.match(parts[2])
                if m:
                    found[parts[2]] = ms_number(m.group("num"))
    return found


def main():
    objdir, out = sys.argv[1], sys.argv[2]
    found = thunks_in(objdir, os.path.splitext(os.path.basename(out))[0] + ".obj")
    lines = [
        "/* Generated by retrofox scripts/vcall-thunks.py: correct vcall thunks for Windows ARM,",
        " * linked ahead of the compiler's copies (which overwrite r1). Don't edit. */",
        "",
        "#if defined(_M_ARM)",
    ]
    for name, offset in sorted(found.items()):
        if offset > 4095:
            sys.exit("vtable offset too large for ldr.w: %s" % name)
        lines += [
            "__asm__(\".section .text$rfxvcall,\\\"xr\\\",discard,\\\"%s\\\"\\n\"" % name,
            "        \".globl \\\"%s\\\"\\n\"" % name,
            "        \".p2align 1\\n.thumb_func\\n\"",
            "        \"\\\"%s\\\":\\n\"" % name,
            "        \"  ldr.w r12, [r0]\\n\"",
            "        \"  ldr.w pc, [r12, #%d]\\n\");" % offset,
        ]
    lines += ["#endif", ""]
    text = "\n".join(lines)
    old = open(out).read() if os.path.exists(out) else None
    if text != old:
        with open(out, "w") as f:
            f.write(text)
    print("%d vcall thunks%s" % (len(found), "" if text != old else " (unchanged)"))


if __name__ == "__main__":
    main()
