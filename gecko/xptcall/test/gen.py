#!/usr/bin/env python3
"""Generates tests.inc for the xptcall Windows-ARM test: an interface with
methods covering the AAPCS-VFP placement cases, an implementation that
records what it receives, the matching xpt method table, and the inputs."""
import struct, sys

SIGS = [
    "i", "bhiB", "qiq", "fdfdf", "iq", "iiq", "iiqi",
    "f" * 17 + "d", "fdddddddf", "d" * 9 + "f", "zcwp",
    "iqfdbhQdzfipwqHdfIcd", "qqq", "iiiiiii", "OdO", "fqfqd",
    "iqdf" * 8, "", "dfffd", "ffdffdffdd",
]
CT = {'b': 'int8_t', 'h': 'int16_t', 'i': 'int32_t', 'q': 'int64_t',
      'B': 'uint8_t', 'H': 'uint16_t', 'I': 'uint32_t', 'Q': 'uint64_t',
      'f': 'float', 'd': 'double', 'z': 'bool', 'c': 'char',
      'w': 'char16_t', 'p': 'void*', 'O': 'int32_t*'}
XT = {'b': 'T_I8', 'h': 'T_I16', 'i': 'T_I32', 'q': 'T_I64', 'B': 'T_U8',
      'H': 'T_U16', 'I': 'T_U32', 'Q': 'T_U64', 'f': 'T_FLOAT',
      'd': 'T_DOUBLE', 'z': 'T_BOOL', 'c': 'T_CHAR', 'w': 'T_WCHAR',
      'p': 'T_INTERFACE', 'O': 'T_I32'}
FIELD = {'b': 'i8', 'h': 'i16', 'i': 'i32', 'q': 'i64', 'B': 'u8',
         'H': 'u16', 'I': 'u32', 'Q': 'u64', 'f': 'f', 'd': 'd', 'z': 'b',
         'c': 'c', 'w': 'wc', 'p': 'p', 'O': 'p'}

def value(t, m, k):
    s = m * 37 + k * 11 + 1
    if t == 'b': v = -((s % 120) + 1); return str(v), v & (2**64 - 1)
    if t == 'h': v = -(s * 101 % 30000 + 1); return str(v), v & (2**64 - 1)
    if t == 'i': v = -(s * 7919 + 100000); return str(v), v & (2**64 - 1)
    if t == 'q': v = -(s * 0x10000000F + 0x123456789); return f"INT64_C({v})", v & (2**64 - 1)
    if t == 'B': v = 200 + s % 50; return f"{v}u", v
    if t == 'H': v = 60000 + s % 5000; return f"{v}u", v
    if t == 'I': v = 0xF0000000 + s; return f"{v}u", v
    if t == 'Q': v = 0xFEDCBA9800000000 + s; return f"UINT64_C({v})", v
    if t == 'f':
        v = s + 0.25
        return f"{v}f", struct.unpack('<I', struct.pack('<f', v))[0]
    if t == 'd':
        v = s * 1000.0 + 0.125
        return f"{v}", struct.unpack('<Q', struct.pack('<d', v))[0]
    if t == 'z': v = s % 2; return ("true" if v else "false"), v
    if t == 'c': v = -(s % 100 + 1); return f"char({v})", v & (2**64 - 1)
    if t == 'w': v = 0x4E00 + s; return f"char16_t({v})", v
    if t in 'pO':
        v = 0x10000000 + s * 16
        return f"({CT[t]})(uintptr_t){v}u", v

out = []
w = out.append
w("/* generated by gen.py */")
w("class ITest : public nsISupports {\npublic:")
for m, sig in enumerate(SIGS):
    args = ", ".join(f"{CT[t]} a{k}" for k, t in enumerate(sig))
    w(f"  NS_IMETHOD M{m}({args}) = 0;")
w("};\n")
w("class TestImpl final : public ITest {\npublic:")
w("  nsresult QueryInterface(const void*, void**) override { return NS_ERROR_FAILURE; }")
w("  uint32_t AddRef() override { return 1; }\n  uint32_t Release() override { return 1; }")
for m, sig in enumerate(SIGS):
    args = ", ".join(f"{CT[t]} a{k}" for k, t in enumerate(sig))
    body = " ".join(f"rec_{t if t not in 'pO' else 'p'}(a{k});" for k, t in enumerate(sig))
    w(f"  nsresult M{m}({args}) override {{ trace_begin(); {body} return nsresult(0x1000 + {m}); }}")
w("};\n")
for m, sig in enumerate(SIGS):
    w(f"static const nsXPTParamInfo kParams{m}[] = {{ " +
      (", ".join(f"{{ nsXPTType(nsXPTType::{XT[t]}), {'true' if t == 'O' else 'false'} }}" for t in sig) or "{ nsXPTType(0), false }") + " };")
w("static const nsXPTMethodInfo kMethods[] = {")
w("  { 0, nullptr }, { 0, nullptr }, { 0, nullptr },")
for m, sig in enumerate(SIGS):
    w(f"  {{ {len(sig)}, kParams{m} }},")
w("};")
w(f"static const uint32_t kMethodCount = {len(SIGS)};")
w(f"static const char* const kSigs[] = {{ {', '.join(repr(s).replace(chr(39), chr(34)) for s in SIGS)} }};\n")

# expected encodings + variant setup
for m, sig in enumerate(SIGS):
    exp = ", ".join(f"UINT64_C({value(t, m, k)[1]})" for k, t in enumerate(sig)) or "0"
    w(f"static const uint64_t kExpect{m}[] = {{ {exp} }};")
w("static const uint64_t* const kExpect[] = { " + ", ".join(f"kExpect{m}" for m in range(len(SIGS))) + " };\n")

w("static void fill_variants(uint32_t m, nsXPTCVariant* v) {\n  switch (m) {")
for m, sig in enumerate(SIGS):
    w(f"  case {m}:")
    for k, t in enumerate(sig):
        lit = value(t, m, k)[0]
        if t == 'O':
            w(f"    v[{k}].type = nsXPTType(nsXPTType::{XT[t]}); v[{k}].flags = nsXPTCVariant::PTR_IS_DATA; v[{k}].ptr = (void*){lit}; v[{k}].val.u64 = 0;")
        else:
            w(f"    v[{k}].type = nsXPTType(nsXPTType::{XT[t]}); v[{k}].flags = 0; v[{k}].val.u64 = UINT64_C(0xDEADBEEFDEADBEEF); v[{k}].val.{FIELD[t]} = {lit};")
    w("    break;")
w("  }\n}\n")

w("static nsresult direct_call(ITest* o, uint32_t m) {\n  switch (m) {")
for m, sig in enumerate(SIGS):
    args = ", ".join(value(t, m, k)[0] for k, t in enumerate(sig))
    w(f"  case {m}: return o->M{m}({args});")
w("  }\n  return NS_ERROR_FAILURE;\n}")
open(sys.argv[1] if len(sys.argv) > 1 else "tests.inc", "w").write("\n".join(out) + "\n")
